from __future__ import annotations

import re
from typing import Any, List, Literal

from pydantic import BaseModel, Field, field_validator, model_validator


def _snake_case_keys(value: Any) -> Any:
    """Models sometimes answer in camelCase; accept both spellings."""
    if not isinstance(value, dict):
        return value
    return {
        re.sub(r"(?<!^)(?=[A-Z])", "_", key).lower() if isinstance(key, str) else key: item
        for key, item in value.items()
    }


class RepositoryMetadata(BaseModel):
    name: str
    owner: str
    description: str | None = None
    default_branch: str
    stars: int
    forks: int
    languages: List[str] = Field(default_factory=list)
    readme: str | None = None


class RepositoryLanguage(BaseModel):
    name: str
    bytes: int
    percentage: float


class RepositoryTreeEntry(BaseModel):
    path: str
    entry_type: str
    sha: str | None = None
    size: int | None = None


class RepositorySourceFile(BaseModel):
    path: str
    content: str


class RepositoryContext(BaseModel):
    """Bounded, trusted GitHub data supplied to the analysis layer."""

    name: str
    owner: str
    description: str | None = None
    stars: int
    forks: int
    default_branch: str
    primary_language: str | None = None
    languages: List[RepositoryLanguage] = Field(default_factory=list)
    readme: str | None = None
    readme_path: str = "README.md"
    readme_truncated: bool = False
    file_tree: List[RepositoryTreeEntry] = Field(default_factory=list)
    file_tree_total: int | None = None
    file_tree_truncated: bool = False
    source_files: List[RepositorySourceFile] = Field(default_factory=list)
    source_files_skipped: int = 0
    source_files_truncated: bool = False


class RepositoryDetails(BaseModel):
    """Repository facts suitable for returning to the dashboard."""

    name: str
    owner: str
    description: str | None = None
    stars: int
    forks: int
    default_branch: str
    primary_language: str | None = None
    languages: List[RepositoryLanguage] = Field(default_factory=list)


CommandKind = Literal["setup", "run", "test", "build", "quality", "other"]


class RunCommand(BaseModel):
    """A command taken from a repository file, never generated by the model."""

    kind: CommandKind
    command: str
    working_directory: str = "."
    source_path: str
    line: int
    # True when the command follows from a file's presence (e.g. a lockfile) rather than being written in it.
    inferred: bool = False


class EntryPoint(BaseModel):
    path: str
    reason: str


class CoverageReport(BaseModel):
    """What RepoLens actually looked at, so readers know the limits of the analysis."""

    readme_found: bool
    readme_truncated: bool
    tree_entries_inspected: int
    tree_entries_total: int | None = None
    tree_truncated: bool
    source_files_inspected: List[str] = Field(default_factory=list)
    source_files_skipped: int = 0


class RepositoryFacts(BaseModel):
    """Deterministically extracted facts; nothing here comes from the model."""

    commands: List[RunCommand] = Field(default_factory=list)
    entry_points: List[EntryPoint] = Field(default_factory=list)
    coverage: CoverageReport


class AnalysisEvidence(BaseModel):
    claim: str
    path: str
    quote: str
    line_start: int = 0
    line_end: int = 0

    @model_validator(mode="before")
    @classmethod
    def normalize_model_keys(cls, value: Any) -> Any:
        return _snake_case_keys(value)


class ReadingStep(BaseModel):
    path: str
    reason: str = ""
    # True only when the path exists in the retrieved file tree.
    verified: bool = False

    @model_validator(mode="before")
    @classmethod
    def normalize(cls, value: Any) -> Any:
        if isinstance(value, str):
            return {"path": value}
        return _snake_case_keys(value)


class Recommendation(BaseModel):
    suggestion: str
    rationale: str = ""
    path: str = ""
    quote: str = ""
    line_start: int = 0
    line_end: int = 0
    # True only when the quote was found verbatim in the cited source file.
    verified: bool = False

    @model_validator(mode="before")
    @classmethod
    def normalize(cls, value: Any) -> Any:
        if isinstance(value, str):
            return {"suggestion": value}
        return _snake_case_keys(value)


class RepositoryAnalysis(BaseModel):
    executive_summary: str
    technologies_used: List[str] = Field(default_factory=list)
    architecture_overview: str
    main_components: List[str] = Field(default_factory=list)
    folder_responsibilities: List[str] = Field(default_factory=list)
    first_steps: List[str] = Field(default_factory=list)
    reading_order: List[ReadingStep] = Field(default_factory=list)
    recommendations: List[Recommendation] = Field(default_factory=list)
    unknowns: List[str] = Field(default_factory=list)
    evidence: List[AnalysisEvidence] = Field(default_factory=list)

    @model_validator(mode="before")
    @classmethod
    def normalize_model_keys(cls, value: Any) -> Any:
        value = _snake_case_keys(value)
        # Older prompts used this name for plain-text recommendations.
        if isinstance(value, dict) and "recommendations" not in value and "suggested_improvements" in value:
            value["recommendations"] = value.pop("suggested_improvements")
        return value

    @field_validator("architecture_overview", mode="before")
    @classmethod
    def coerce_text_field(cls, value: Any) -> Any:
        if isinstance(value, list):
            return " ".join(str(item) for item in value)
        return value

    @field_validator(
        "technologies_used",
        "main_components",
        "folder_responsibilities",
        "first_steps",
        "unknowns",
        mode="before",
    )
    @classmethod
    def coerce_list_fields(cls, value: Any) -> Any:
        if isinstance(value, dict):
            return [f"{key}: {item}" for key, item in value.items()]
        if isinstance(value, str):
            return [value]
        if isinstance(value, list):
            return [
                "; ".join(f"{key}: {item}" for key, item in entry.items())
                if isinstance(entry, dict)
                else str(entry)
                for entry in value
            ]
        return value

    @field_validator("reading_order", "recommendations", mode="before")
    @classmethod
    def coerce_object_lists(cls, value: Any) -> Any:
        if isinstance(value, (str, dict)):
            return [value]
        return value


class RepositoryAnalysisResult(BaseModel):
    repository: RepositoryDetails
    facts: RepositoryFacts | None = None
    analysis: RepositoryAnalysis
